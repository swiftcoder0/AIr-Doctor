def execute_approval_action(
    approval_id: str,
    req: ApprovalActionRequest,
    db: Session,
) -> ApprovalActionResponse:
    """
    Executes Commander decision on a pending operational item.
    Cryptographically commits the decision to DecisionLedgerORM with SHA-256 hash chaining.
    """
    target = next((a for a in COMMANDER_APPROVALS if a["id"] == approval_id), None)
    if not target:
        raise ValueError(f"Approval request {approval_id} not found.")

    status_map = {
        "APPROVE": "APPROVED",
        "REJECT": "REJECTED",
        "CLARIFY": "CLARIFICATION_REQUESTED",
    }
    new_status = status_map.get(req.action.upper(), "APPROVED")
    now_iso = datetime.now(timezone.utc).isoformat()
    now_display = datetime.now(timezone.utc).strftime("%d %b %Y %H:%M UTC")

    # 1. Update in-memory approval record
    target["status"] = new_status
    target["decisionNotes"] = req.notes
    target["decidedBy"] = req.officer_name or "Wing Cmdr. Aditya (Fleet Commander)"
    target["decidedAt"] = now_display

    # 2. Cryptographically commit into DecisionLedgerORM
    ledger_id = f"DL-CMD-{str(uuid.uuid4())[:8].upper()}"

    # Get the latest ledger entry to chain SHA-256 hash
    last_entry = db.query(DecisionLedgerORM).order_by(DecisionLedgerORM.timestamp.desc()).first()
    prev_hash = GENESIS_HASH
    if last_entry:
        # compute block hash of the predecessor
        prev_hash = compute_block_hash(
            prev_hash=GENESIS_HASH,
            entry_id=last_entry.id,
            timestamp=last_entry.timestamp,
            actor=last_entry.actor,
            action=last_entry.action,
            resulting_state=last_entry.resulting_state,
        )

    actor_str = req.officer_name or "Wing Cmdr. Aditya (Fleet Commander)"
    action_str = f"COMMANDER_{req.action.upper()}_{target['type'].upper().replace(' ', '_')}"
    resulting_str = f"Approval {target['id']} marked {new_status} for {target['aircraft']} at {target['baseName']}"

    ledger_entry = DecisionLedgerORM(
        id=ledger_id,
        timestamp=now_iso,
        actor=actor_str,
        action=action_str,
        previous_state=f"Status: PENDING | Priority: {target['priority']} | Justification: {target['justification'][:80]}...",
        resulting_state=resulting_str,
        notes=f"Commander Decision Notes: {req.notes}. Impact: {target['impact']}",
        scenario_id=target["id"],
        base_id=target["baseName"].split()[0].lower(),
        is_override=(req.action.upper() == "APPROVE"),
        override_reason=req.notes if req.action.upper() == "APPROVE" else None,
    )
    db.add(ledger_entry)
    db.commit()
    db.refresh(ledger_entry)

    # Compute this block's SHA-256 hash
    curr_hash = compute_block_hash(
        prev_hash=prev_hash,
        entry_id=ledger_id,
        timestamp=now_iso,
        actor=actor_str,
        action=action_str,
        resulting_state=resulting_str,
    )

    target["ledgerEntryId"] = ledger_id
    target["ledgerHash"] = curr_hash

    return ApprovalActionResponse(
        success=True,
        message=f"Decision {new_status} recorded successfully for {target['id']}. Block {ledger_id} chained into Decision Ledger.",
        approval=CommandApprovalItem(**target),
        ledger_entry_id=ledger_id,
        ledger_hash=curr_hash,
    )
